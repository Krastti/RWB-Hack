"""A-34 deterministic TS projection plus Angular Reactive Forms consumer."""
from hashlib import sha256
import json
from pathlib import Path
from ...model import bind, blockers, canonical, checksum, require, validate_model

COMPILER_VERSION='typescript-1.0.2'
ROOT=Path(__file__).parent
POLICY='frontend/src/app/domain/policy.ts'
COMPONENT='frontend/src/app/domain/domain-action.ts'
BINDINGS='frontend/src/app/domain/ui-bindings.ts'
MAP='frontend/src/app/domain/policy.map.json'


def emit(model, *, catalog, profile):
    model=json.loads(canonical(model))
    require(profile.profile_id == 'web-fastapi-angular' and
            profile.profile_version in {'1.1.0', '1.2.0'} and
            profile.allows('architecture', 'behavior-bindings.json'), 'BEHAVIOR_PROFILE_MISMATCH')
    limits=profile.data['limits'].get('behavior')
    require(isinstance(limits,dict), 'BEHAVIOR_PROFILE_MISMATCH')
    validate_model(model,max_bytes=limits['max_model_bytes'],
                   max_expression_depth=limits['max_expression_depth'],
                   max_rules=limits['max_rules'],max_domain_values=limits['max_domain_values'])
    require(model['bindings'] is not None and not blockers(model) and all(r['status']=='supported' for r in model['rules']),'BEHAVIOR_CODEGEN_BLOCKED')
    bind(model,model['bindings'],catalog)
    # No unbounded text/user-id form widgets or guessing domains in first emitter.
    require(all(p['type']['kind']!='identity' for a in model['actions'] for p in a['parameters']),'BEHAVIOR_IDENTITY_FORM_UNSUPPORTED')
    header='// Generated by '+COMPILER_VERSION+'; model '+checksum(model)+'\n'
    source=header+(ROOT/'runtime.ts').read_text()+'\nconst MODEL = '+canonical(model)+' as Model;\n'
    bindings=[{'action_id':a['id'],**model['bindings']['actions'][a['id']]} for a in model['actions']]
    files={POLICY:source,COMPONENT:header+(ROOT/'component.ts').read_text(),BINDINGS:header+'export const UI_BINDINGS = '+canonical(bindings)+' as const;\n'}
    mapping=dict(schema_version='1.0',compiler_version=COMPILER_VERSION,model_checksum=checksum(model),contract_version=model['contract_version'],owner_agent='frontend',input_checksum=checksum({'model':model,'catalog':catalog,'profile':profile.metadata}),files={p:sha256(c.encode()).hexdigest() for p,c in sorted(files.items())},rules=[{'rule_id':r['id'],'fr_ids':r['fr_ids'],'path':POLICY,'symbol':'decide','action_id':r['action'],'enforced':r['kind']!='invariant'} for r in sorted(model['rules'],key=lambda r:r['id'])],limitations=['Independent invariants are simulation assertions, not UI guards.','A-11 must place DomainActionComponent using UI_BINDINGS and its accepted gateway.'])
    files[MAP]=canonical(mapping)+'\n'
    require(all(profile.allows('frontend',p) for p in files),'BEHAVIOR_CODEGEN_GRANT_MISSING')
    require(all(len(c.encode())<=profile.data['limits']['artifacts']['max_file_bytes'] for c in files.values()),'BEHAVIOR_CODEGEN_SIZE_LIMIT')
    return files
